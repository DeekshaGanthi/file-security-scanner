-- 1. File scan records
CREATE TABLE scans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    file_type TEXT,
    file_size INTEGER,
    risk_score INTEGER,
    risk_level TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Security indicators associated with scans
CREATE TABLE indicators (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id INTEGER REFERENCES scans(id),
    indicator_type TEXT,
    indicator_name TEXT,
    severity TEXT
);

-- 3. AI-generated analysis reports
CREATE TABLE llm_reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id INTEGER REFERENCES scans(id),
    model TEXT,
    report TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
